function fail(message) {
  failures.push(message);
}

function toPosix(value) {
  return value
    .split(sep)
    .join("/");
}

function displayPath(
  absolutePath,
) {
  return (
    toPosix(
      relative(
        REPO_ROOT,
        absolutePath,
      ),
    ) || "."
  );
}

function backendRelativePath(
  absolutePath,
) {
  return toPosix(
    relative(
      BACKEND_ROOT,
      absolutePath,
    ),
  );
}

function readRequiredFile(
  absolutePath,
  code,
) {
  if (
    !existsSync(absolutePath)
  ) {
    fail(
      `[${code}] required source/document file is missing: ` +
        `${displayPath(absolutePath)}`,
    );

    return null;
  }

  return readFileSync(
    absolutePath,
    "utf8",
  );
}

function setsEqual(
  left,
  right,
) {
  if (
    left.size !== right.size
  ) {
    return false;
  }

  for (
    const value of left
  ) {
    if (
      !right.has(value)
    ) {
      return false;
    }
  }

  return true;
}

function setDifference(
  left,
  right,
) {
  return [
    ...left,
  ].filter(
    (value) =>
      !right.has(value),
  );
}

/**
 * Discover actual production .csproj files below backend/src.
 *
 * We deliberately derive this from source rather than trusting only
 * backend.slnx.
 *
 * Otherwise a new production project could exist in source but remain
 * accidentally absent from the solution.
 */
function discoverBackendProductionProjects() {
  const sourceRoot =
    join(
      BACKEND_ROOT,
      "src",
    );

  const discovered = [];

  if (
    !existsSync(sourceRoot)
  ) {
    fail(
      `[BACKEND_SOURCE] backend source directory is missing: ` +
        `${displayPath(sourceRoot)}`,
    );

    return discovered;
  }

  function walk(directory) {
    for (
      const entry of readdirSync(
        directory,
        {
          withFileTypes: true,
        },
      )
    ) {
      if (
        entry.isDirectory() &&
        (
          entry.name === "bin" ||
          entry.name === "obj"
        )
      ) {
        continue;
      }

      const absolutePath =
        join(
          directory,
          entry.name,
        );

      if (
        entry.isDirectory()
      ) {
        walk(absolutePath);
        continue;
      }

      if (
        entry.isFile() &&
        entry.name.endsWith(
          ".csproj",
        )
      ) {
        discovered.push(
          backendRelativePath(
            absolutePath,
          ),
        );
      }
    }
  }

  walk(sourceRoot);

  return discovered.sort(
    (a, b) =>
      a.localeCompare(
        b,
        "en",
      ),
  );
}

/**
 * backend.slnx is intentionally simple XML-like text.
 *
 * We only need Project Path attributes.
 */
function parseSolutionProjects(
  text,
) {
  const projects = [];

  const pattern =
    /<Project\s+Path="([^"]+\.csproj)"\s*\/?>/g;

  for (
    const match of text.matchAll(
      pattern,
    )
  ) {
    projects.push(
      toPosix(
        match[1],
      ),
    );
  }

  return projects;
}

function validateBackendProductionInventory() {
  const solutionText =
    readRequiredFile(
      BACKEND_SOLUTION,
      "BACKEND_SOLUTION",
    );

  const overviewText =
    readRequiredFile(
      BACKEND_OVERVIEW,
      "BACKEND_OVERVIEW",
    );

  if (
    solutionText == null ||
    overviewText == null
  ) {
    return;
  }

  const expectedPaths =
    new Set(
      BACKEND_PRODUCTION_PROJECTS.map(
        (project) =>
          project.path,
      ),
    );

  const discoveredPaths =
    new Set(
      discoverBackendProductionProjects(),
    );

  /**
   * Source production project set must remain exactly the approved
   * architecture set.
   */
  if (
    !setsEqual(
      expectedPaths,
      discoveredPaths,
    )
  ) {
    for (
      const missing of setDifference(
        expectedPaths,
        discoveredPaths,
      )
    ) {
      fail(
        `[BACKEND_PROJECT_MISSING] approved backend production project ` +
          `does not exist in source: backend/${missing}`,
      );
    }

    for (
      const unexpected of setDifference(
        discoveredPaths,
        expectedPaths,
      )
    ) {
      fail(
        `[BACKEND_PROJECT_UNEXPECTED] unapproved backend production project ` +
          `exists under backend/src: backend/${unexpected}. ` +
          `Adding a production project requires architecture review.`,
      );
    }
  }

  const solutionProjects =
    new Set(
      parseSolutionProjects(
        solutionText,
      ),
    );

  for (
    const project of
      BACKEND_PRODUCTION_PROJECTS
  ) {
    if (
      !solutionProjects.has(
        project.path,
      )
    ) {
      fail(
        `[BACKEND_SOLUTION_MISSING] backend/backend.slnx does not contain ` +
          `${project.path}`,
      );
    }

    if (
      !overviewText.includes(
        project.name,
      )
    ) {
      fail(
        `[BACKEND_DOC_INVENTORY] backend overview does not document ` +
          `production project ${project.name}`,
      );
    }
  }

  /**
   * A production project under backend/src must also be part of the
   * solution.
   */
  for (
    const projectPath of
      discoveredPaths
  ) {
    if (
      !solutionProjects.has(
        projectPath,
      )
    ) {
      fail(
        `[BACKEND_SOLUTION_DRIFT] production project exists in source but ` +
          `is missing from backend/backend.slnx: backend/${projectPath}`,
      );
    }
  }

  if (
    !overviewText.includes(
      "backend.slnx",
    )
  ) {
    fail(
      `[BACKEND_DOC_INVENTORY] backend overview should route the reader to ` +
        `backend/backend.slnx as current solution inventory evidence`,
    );
  }
}

/**
 * Parse only the `packages:` list from pnpm-workspace.yaml.
 *
 * We intentionally do not parse catalog/version data here.
 *
 * This avoids making root documentation governance responsible for
 * frontend dependency-version semantics.
 */
function parseWorkspacePackagePatterns(
  text,
) {
  const lines =
    text.split(/\r?\n/);

  const patterns = [];

  let inPackages = false;

  for (
    const line of lines
  ) {
    if (
      /^\s*packages:\s*$/.test(
        line,
      )
    ) {
      inPackages = true;
      continue;
    }

    if (
      inPackages &&
      /^[A-Za-z0-9_-]+:\s*$/.test(
        line,
      )
    ) {
      break;
    }

    if (!inPackages) {
      continue;
    }

    const match =
      line.match(
        /^\s+-\s+["']?([^"']+)["']?\s*$/,
      );

    if (match) {
      patterns.push(
        match[1].trim(),
      );
    }
  }

  return patterns;
}

function validateFrontendWorkspaceFamilies() {
  const workspaceText =
    readRequiredFile(
      FRONTEND_WORKSPACE,
      "FRONTEND_WORKSPACE",
    );

  const overviewText =
    readRequiredFile(
      FRONTEND_OVERVIEW,
      "FRONTEND_OVERVIEW",
    );

  if (
    workspaceText == null ||
    overviewText == null
  ) {
    return;
  }

  const expected =
    new Set(
      FRONTEND_WORKSPACE_FAMILIES,
    );

  const actualPatterns =
    parseWorkspacePackagePatterns(
      workspaceText,
    );

  const actual =
    new Set(
      actualPatterns,
    );

  /**
   * Duplicate workspace globs are almost certainly configuration debt.
   */
  if (
    actual.size !==
    actualPatterns.length
  ) {
    const seen =
      new Set();

    for (
      const pattern of
        actualPatterns
    ) {
      if (
        seen.has(pattern)
      ) {
        fail(
          `[FRONTEND_WORKSPACE_DUPLICATE] duplicate pnpm workspace pattern: ` +
            `${pattern}`,
        );
      }

      seen.add(pattern);
    }
  }

  if (
    !setsEqual(
      expected,
      actual,
    )
  ) {
    for (
      const missing of setDifference(
        expected,
        actual,
      )
    ) {
      fail(
        `[FRONTEND_WORKSPACE_MISSING] pnpm workspace is missing approved ` +
          `package family: ${missing}`,
      );
    }

    for (
      const unexpected of setDifference(
        actual,
        expected,
      )
    ) {
      fail(
        `[FRONTEND_WORKSPACE_UNEXPECTED] pnpm workspace contains an ` +
          `unreviewed package-family pattern: ${unexpected}. ` +
          `Workspace-family changes require architecture synchronization.`,
      );
    }
  }

  /**
   * Human architecture docs should explain package families.
   *
   * They should NOT enumerate every exact package.
   */
  for (
    const [
      family,
      acceptedTokens,
    ] of
      FRONTEND_OVERVIEW_FAMILY_TOKENS
  ) {
    const documented =
      acceptedTokens.some(
        (token) =>
          overviewText.includes(
            token,
          ),
      );

    if (!documented) {
      fail(
        `[FRONTEND_DOC_INVENTORY] frontend overview does not document ` +
          `workspace family ${family}; expected one of: ` +
          `${acceptedTokens.join(", ")}`,
      );
    }
  }
}

function dependencyMap(
  packageJson,
) {
  return {
    ...(packageJson.dependencies ?? {}),
    ...(packageJson.devDependencies ?? {}),
    ...(packageJson.peerDependencies ?? {}),
    ...(packageJson.optionalDependencies ?? {}),
  };
}

function readPackageJson(
  absolutePath,
) {
  const text =
    readRequiredFile(
      absolutePath,
      "FRONTEND_PACKAGE_JSON",
    );

  if (
    text == null
  ) {
    return null;
  }

  try {
    return JSON.parse(text);
  } catch (error) {
    fail(
      `[FRONTEND_PACKAGE_JSON] invalid JSON in ${displayPath(absolutePath)}: ` +
        `${error.message}`,
    );

    return null;
  }
}

function validateFrontendHosts() {
  const overviewText =
    readRequiredFile(
      FRONTEND_OVERVIEW,
      "FRONTEND_OVERVIEW",
    );

  if (
    overviewText == null
  ) {
    return;
  }

  for (
    const host of
      FRONTEND_HOSTS
  ) {
    const packagePath =
      join(
        FRONTEND_ROOT,
        host.path,
        "package.json",
      );

    const packageJson =
      readPackageJson(
        packagePath,
      );

    if (
      packageJson == null
    ) {
      continue;
    }

    if (
      packageJson.name !==
      host.packageName
    ) {
      fail(
        `[FRONTEND_HOST_NAME] ${displayPath(packagePath)} must declare ` +
          `name ${host.packageName}; got ${packageJson.name ?? "<missing>"}`,
      );
    }

    const dependencies =
      dependencyMap(
        packageJson,
      );

    if (
      !Object.prototype.hasOwnProperty.call(
        dependencies,
        host.frameworkDependency,
      )
    ) {
      fail(
        `[FRONTEND_HOST_FRAMEWORK] ${host.packageName} does not declare its ` +
          `expected host-framework dependency ${host.frameworkDependency}`,
      );
    }

    for (
      const token of
        host.overviewTokens
    ) {
      if (
        !overviewText.includes(
          token,
        )
      ) {
        fail(
          `[FRONTEND_HOST_DOC] frontend overview does not contain host token ` +
            `${token} for ${host.packageName}`,
        );
      }
    }
  }
}

function validateFrontendArchitectureManifestPresence() {
  if (
    !existsSync(
      FRONTEND_ARCHITECTURE_MANIFEST,
    )
  ) {
    fail(
      `[FRONTEND_MANIFEST_MISSING] frontend closed-world architecture manifest ` +
        `is missing: ${displayPath(FRONTEND_ARCHITECTURE_MANIFEST)}`,
    );

    return;
  }

  /**
   * We deliberately do NOT parse the exact package array here.
   *
   * That would duplicate the frontend dependency-rule tool's own
   * executable authority.
   */
  const text =
    readFileSync(
      FRONTEND_ARCHITECTURE_MANIFEST,
      "utf8",
    );

  if (
    !text.includes(
      "ARCHITECTURE_MANIFEST",
    )
  ) {
    fail(
      `[FRONTEND_MANIFEST_SHAPE] ${displayPath(FRONTEND_ARCHITECTURE_MANIFEST)} ` +
        `does not expose ARCHITECTURE_MANIFEST`,
    );
  }
}

if (
  !existsSync(REPO_ROOT)
) {
  console.error(
    `[docs-source-inventory] repository root does not exist: ${REPO_ROOT}`,
  );

  process.exit(1);
}

validateBackendProductionInventory();

validateFrontendWorkspaceFamilies();

validateFrontendHosts();

validateFrontendArchitectureManifestPresence();

if (
  failures.length > 0
) {
  console.error(
    `[docs-source-inventory] FAIL — ${failures.length} source-inventory violation(s):`,
  );

  for (
    const failure of failures
  ) {
    console.error(
      `- ${failure}`,
    );
  }

  process.exit(1);
}

console.log(
  `[docs-source-inventory] PASS — ` +
    `${BACKEND_PRODUCTION_PROJECTS.length} backend production project(s), ` +
    `${FRONTEND_WORKSPACE_FAMILIES.length} frontend workspace family/families, ` +
    `${FRONTEND_HOSTS.length} frontend host(s).`,
);